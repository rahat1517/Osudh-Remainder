"""Generates lib/l10n/codes.dart from spec/api/codes.json.

    python3 tool/gen_codes.py

Each code maps to an ARB key: errors → err<CamelCase>, notices → notice<CamelCase>.
Notices with parameters are listed in PARAMS. test/localized_codes_test.dart checks coverage.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT.parent / "spec" / "api" / "codes.json"
OUT = ROOT / "lib" / "l10n" / "codes.dart"

PARAMS = {
    "name_corrected": "written",
    "strength_not_in_catalog": "written",
    "strength_suggested": "suggested",
    "dose_unreadable": "written",
    "duration_out_of_range": "days",
}


def camel(prefix: str, code: str) -> str:
    return prefix + "".join(part.capitalize() for part in code.split("_"))


def main() -> None:
    codes = json.loads(SPEC.read_text(encoding="utf-8"))
    lines = [
        "// GENERATED by tool/gen_codes.py from spec/api/codes.json. Do not edit by hand.",
        "",
        "/// Maps backend codes to localized text.",
        "library;",
        "",
        "import '../data/models.dart';",
        "import 'generated/app_localizations.dart';",
        "",
        "/// Localized text for an error code, or null if the code is unknown.",
        "String? localizeError(AppLocalizations l, String code) => switch (code) {",
    ]
    lines += [f"  '{c}' => l.{camel('err', c)}," for c in codes["errors"]]
    lines += [
        "  'network_error' => l.errorNetwork,",
        "  _ => null,",
        "};",
        "",
        "/// Localized text for a notice, with its parameters filled in.",
        "String? localizeNotice(AppLocalizations l, Notice n) {",
        "  String p(String key) => n.params[key] ?? '';",
        "  return switch (n.code) {",
    ]
    for c in codes["notices"]:
        arg = f"(p('{PARAMS[c]}'))" if c in PARAMS else ""
        lines.append(f"    '{c}' => l.{camel('notice', c)}{arg},")
    lines += ["    _ => null,", "  };", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
